// Independent 2026-11-15 arithmetic verification of OEIS A328151.
// Uses Dirichlet's divisor-character identity for sums of two squares,
// and Euclid's primitive Pythagorean triples for triangle counts.
// No repository code or tables used.
#include <algorithm>
#include <chrono>
#include <cmath>
#include <cstdint>
#include <cstdlib>
#include <iostream>
#include <numeric>
#include <vector>
using namespace std;
int main(int argc, char** argv) {
  if (argc != 2) { cerr << "usage: verifier LIMIT\n"; return 2; }
  const int limit = atoi(argv[1]);
  if (limit < 2) return 2;
  const auto started = chrono::steady_clock::now();
  // s(n) = sum_{d|n} chi_4(d). Thus r_2(n) = 4*s(n).
  // R(n) = s(n) - [n is a square], and D(n) =
  // (R(n)-[n is twice a square])/2 for n > 0.
  vector<int16_t> s(limit+1, 0);
  for (int d=1; d<=limit; d+=2) {
    const int sign = (d % 4 == 1) ? 1 : -1;
    for (int n=d; n<=limit; n+=d) s[n] += sign;
  }
  const int mmax = int(sqrtl((long double)limit/2));
  vector<int> triangles(mmax+1, 0);
  // Every integer right triangle is an integer multiple of exactly
  // one primitive Euclid triple, generated by a>b>=1, coprime and
  // of opposite parity, primitive hypotenuse a*a+b*b.
  for (int a=2; a*a+1<=mmax; ++a) {
    for (int b=1; b<a && a*a+b*b<=mmax; ++b) {
      if ((a-b)%2==0 || gcd(a,b)!=1) continue;
      const int h=a*a+b*b;
      for (int m=h; m<=mmax; m+=h) ++triangles[m];
    }
  }
  vector<int64_t> min_r(512, -1), min_d(512, -1);
  min_r[0]=0; min_d[0]=0;
  int root=0, nextsq=1;
  int diagroot=0, nextdiag=2;
  int64_t wrong_arithmetic=0;
  for (int n=1; n<=limit; ++n) {
    if (n==nextsq) {
      ++root;
      nextsq=(root+1)*(int64_t)(root+1)>limit ? limit+1 : (root+1)*(root+1);
    }
    if (n==nextdiag) {
      ++diagroot;
      nextdiag=2*(diagroot+1)*(int64_t)(diagroot+1)>limit ? limit+1 : 2*(diagroot+1)*(diagroot+1);
    }
    const int R = s[n] - (n==(int64_t)root*root);
    const int D = (R-(n==2*(int64_t)diagroot*diagroot))/2;
    if (R<0 || R>511 || D<0 || D>511 || (R-2*D != (n==2*(int64_t)diagroot*diagroot))) {
      ++wrong_arithmetic;
      continue;
    }
    if (min_r[R]==-1) min_r[R]=n;
    if (min_d[D]==-1) min_d[D]=n;
  }
  int64_t mismatch_bijection=0, mismatch_odd=0, mismatch_even=0;
  for (int m=1; m<=mmax; ++m) {
    const int R=s[2*m*m] - 0; // 2m^2 is not an integer square.
    const int D2=(R-1)/2;
    const int D1=(s[m*m]-1)/2; // m^2 has exactly four axial points.
    if (D1!=triangles[m] || D2!=triangles[m] || R!=2*triangles[m]+1) ++mismatch_bijection;
  }
  // First m producing T(m)=k: checks *odd minima* without trusting
  // the repository's predicted-minimum optimization.
  vector<int> first_h(512, 0);
  for (int m=1; m<=mmax; ++m)
    if (triangles[m]<512 && !first_h[triangles[m]]) first_h[triangles[m]]=m;
  int odd_checked=0, even_checked=0;
  for (int k=0; k<256; ++k) {
    if (first_h[k] && min_r[2*k+1]>=0) {
      ++odd_checked;
      if (min_r[2*k+1]!=2LL*first_h[k]*first_h[k]) ++mismatch_odd;
    }
    if (k>=1 && min_d[k]>=0 && min_r[2*k]>=0) {
      ++even_checked;
      if (min_r[2*k]!=min_d[k]) ++mismatch_even;
    }
  }
  const auto elapsed=chrono::duration<double>(chrono::steady_clock::now()-started).count();
  cout << "algorithm=Dirichlet chi4 divisor sieve + Euclid primitive triples\n";
  cout << "limit_N=" << limit << " m_max=" << mmax << "\n";
  cout << "identity_m_tested=" << mmax << " mismatches=" << mismatch_bijection << "\n";
  cout << "even_k_tested=" << even_checked << " mismatches=" << mismatch_even << "\n";
  cout << "odd_k_tested=" << odd_checked << " mismatches=" << mismatch_odd << "\n";
  cout << "arithmetic_mismatches=" << wrong_arithmetic << "\n";
  cout << "even_pairs(k,minimum):";
  for (int k=1; k<256; ++k)
    if (min_d[k]>=0 && min_r[2*k]>=0) cout << " (" << k << "," << min_r[2*k] << ")";
  cout << "\nodd_pairs(k,minimum,m):";
  for (int k=0; k<256; ++k)
    if (first_h[k] && min_r[2*k+1]>=0) cout << " (" << k << "," << min_r[2*k+1] << "," << first_h[k] << ")";
  cout << "\n";
  cout << "wall_clock_seconds=" << elapsed << "\n";
  const bool pass = !mismatch_bijection && !mismatch_odd && !mismatch_even && !wrong_arithmetic;
  cout << (pass?"PASS":"FAIL") << "\n";
  return pass?0:1;
}
